#!/usr/bin/env bash
set -Eeuo pipefail
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
PROFILE="$ROOT/manjaro/venom-mate"
fail() { printf 'FALHA: %s\n' "$*" >&2; exit 1; }
pass() { printf 'OK: %s\n' "$*"; }

for f in profile.conf Packages-Root Packages-Desktop Packages-Live Packages-Mhwd; do
  [[ -s "$PROFILE/$f" ]] || fail "arquivo de perfil ausente: $f"
done
[[ -s "$PROFILE/desktop-overlay/usr/local/bin/manjaro-mate-dark-complete.sh" ]] || fail "script original ausente do overlay"
[[ -s "$PROFILE/desktop-overlay/usr/share/mate-panel/layouts/manjaro.layout" ]] || fail "layout Manjaro MATE ausente"
[[ -s "$PROFILE/desktop-overlay/usr/share/applications/venom-mate-setup.desktop" ]] || fail "atalho do configurador ausente"
[[ -s "$PROFILE/desktop-overlay/etc/skel/.config/gtk-3.0/settings.ini" ]] || fail "padrões GTK3 ausentes"
[[ -s "$PROFILE/desktop-overlay/etc/skel/.config/gtk-4.0/settings.ini" ]] || fail "padrões GTK4 ausentes"
[[ -s "$PROFILE/desktop-overlay/etc/skel/.icons/default/index.theme" ]] || fail "cursor Bibata padrão ausente"
[[ -s "$PROFILE/desktop-overlay/etc/skel/.config/autostart/venom-theme-defaults.desktop" ]] || fail "inicialização dos temas ausente"
[[ -s "$PROFILE/desktop-overlay/usr/local/bin/venom-theme-defaults" ]] || fail "aplicador dos temas ausente"
grep -Fxq 'materia-gtk-theme' "$PROFILE/Packages-Desktop" || fail "tema Materia ausente"
grep -Fxq 'papirus-icon-theme' "$PROFILE/Packages-Desktop" || fail "tema Papirus ausente"
grep -Fq 'Materia-dark' "$PROFILE/desktop-overlay/etc/skel/.config/gtk-3.0/settings.ini" || fail "Materia Dark não é o padrão GTK3"
grep -Fq 'Papirus-Dark' "$PROFILE/desktop-overlay/etc/skel/.config/gtk-3.0/settings.ini" || fail "Papirus-Dark não é o padrão GTK3"
grep -Fq 'Bibata-Modern-Classic' "$PROFILE/desktop-overlay/etc/skel/.icons/default/index.theme" || fail "Bibata não é o cursor padrão"
bash -n "$PROFILE/desktop-overlay/usr/local/bin/venom-theme-defaults" || fail "sintaxe do aplicador de temas inválida"
[[ -s "$PROFILE/desktop-overlay/etc/locale.conf" ]] || fail "locale PT-BR ausente"
[[ -s "$PROFILE/desktop-overlay/etc/vconsole.conf" ]] || fail "teclado ABNT2 ausente"
[[ -s "$PROFILE/desktop-overlay/etc/X11/xorg.conf.d/00-keyboard.conf" ]] || fail "teclado X11 ABNT2 ausente"
grep -Fxq 'LANG=pt_BR.UTF-8' "$PROFILE/desktop-overlay/etc/locale.conf" || fail "locale pt_BR inválido"
grep -Fxq 'KEYMAP=br-abnt2' "$PROFILE/desktop-overlay/etc/vconsole.conf" || fail "console ABNT2 inválido"
grep -Fq 'XkbVariant" "abnt2' "$PROFILE/desktop-overlay/etc/X11/xorg.conf.d/00-keyboard.conf" || fail "X11 ABNT2 inválido"
cmp -s "$ROOT/scripts/manjaro-mate-dark-complete.sh" "$PROFILE/desktop-overlay/usr/local/bin/manjaro-mate-dark-complete.sh" || fail "cópia do script diverge do original"
bash -n "$ROOT/scripts/manjaro-mate-dark-complete.sh" || fail "sintaxe do script original inválida"
grep -Fq "manjaro-mate-settings" "$ROOT/scripts/manjaro-mate-dark-complete.sh" && fail "pacote MATE descontinuado ainda está no script" || true
bash -n "$ROOT/scripts/build-venom-iso.sh" || fail "sintaxe do construtor inválida"
! grep -Eiq 'calamares|archiso|endeavouros' "$PROFILE/Packages-Root" "$PROFILE/Packages-Desktop" "$PROFILE/Packages-Live" "$PROFILE/profile.conf" || fail "componente proibido no perfil ativo"
grep -Fxq 'mate' "$PROFILE/Packages-Desktop" || fail "grupo MATE ausente"
grep -Fxq 'mate-extra' "$PROFILE/Packages-Desktop" || fail "grupo MATE Extra ausente"
grep -Fxq 'mate-media' "$PROFILE/Packages-Desktop" || fail "controle de volume MATE ausente"
grep -Fxq 'network-manager-applet' "$PROFILE/Packages-Desktop" || fail "indicador de rede ausente"
grep -Fxq 'blueman' "$PROFILE/Packages-Desktop" || fail "gerenciador Bluetooth ausente"
grep -Fxq 'bluez' "$PROFILE/Packages-Desktop" || fail "serviço Bluetooth ausente"
grep -Fxq 'pipewire-pulse' "$PROFILE/Packages-Desktop" || fail "áudio PulseAudio compatível com PipeWire ausente"
grep -Fxq 'wireplumber' "$PROFILE/Packages-Desktop" || fail "gerenciador de áudio WirePlumber ausente"
grep -Fq 'applet-iid=GvcAppletFactory::GvcApplet' "$PROFILE/desktop-overlay/usr/share/mate-panel/layouts/manjaro.layout" || fail "applet de volume ausente no painel"
grep -Fq 'applet-iid=NotificationAreaAppletFactory::NotificationArea' "$PROFILE/desktop-overlay/usr/share/mate-panel/layouts/manjaro.layout" || fail "bandeja de sistema ausente no painel"
grep -Fxq 'lightdm' "$PROFILE/Packages-Desktop" || fail "LightDM ausente"
grep -Fq 'displaymanager="lightdm"' "$PROFILE/profile.conf" || fail "LightDM não selecionado"
grep -Fq "enable_systemd=('bluetooth' 'NetworkManager' 'lightdm' 'systemd-timesyncd')" "$PROFILE/profile.conf" || fail "serviços de rede e Bluetooth não habilitados"
grep -Fq 'Manjaro Linux' "$ROOT/README.md" || fail "base Manjaro não documentada"
pass "perfil Manjaro MATE, LightDM e pacotes"
pass "script DeepSeek preservado byte a byte no overlay"
pass "nenhum Calamares, Archiso ou EndeavourOS no perfil ativo"
